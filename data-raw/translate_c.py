"""Translate the QFracture-2012 C equations (ClinRisk, LGPL-3) into R.

usage: python3 -I data-raw/translate_c.py <dir with Q74_*.c> R/equations.R

Source: github.com/nhsland/clinrisk-modules, commit 4e7cb71e, qFracture/c/
(mirror of http://svn.clinrisk.co.uk/qfracture). Each auto-generated
*_raw() function is translated statement by statement; numbers are copied
as written. C arrays are 0-based, so an index i becomes [i + 1] in R.
"""
import re, sys, os

FILES = [("Q74_qfracture4_2012_2_0.c", "fracture4_female"), ("Q74_qfracture4_2012_2_1.c", "fracture4_male"),
         ("Q74_qnof_2012_2_0.c", "nof_female"), ("Q74_qnof_2012_2_1.c", "nof_male")]

def pow_to_caret(s):
    """Rewrite every pow(x, y) as (x)^(y), matching nested brackets."""
    while True:
        i = s.find("pow(")
        if i < 0:
            return s
        depth, j, comma = 0, i + 3, None
        while True:
            c = s[j]
            if c in "([":
                depth += 1
            elif c in ")]":
                depth -= 1
                if depth == 0:
                    break
            elif c == "," and depth == 1:
                comma = j
            j += 1
        s = s[:i] + "(" + s[i + 4:comma].strip() + ")^(" + s[comma + 1:j].strip() + ")" + s[j + 1:]

def translate(src, name):
    m = re.search(r"static double %s_raw\(\s*(.*?)\)\s*\{(.*?)\n\}" % name, src, re.S)
    params = [p.split()[-1] for p in m.group(1).split(",")]
    body = m.group(2)
    arrays = re.findall(r"double (\w+)\[\d+\]\s*=\s*\{(.*?)\};", body, re.S)
    out = ["%s_raw <- function(%s) {" % (name, ", ".join(params))]
    for an, vals in arrays:
        nums = [v.strip() for v in vals.replace("\n", " ").split(",") if v.strip()]
        out.append("  %s <- c(%s)" % (an, ", ".join(nums)))
    names = {an for an, _ in arrays}
    rest = re.sub(r"double \w+\[\d+\]\s*=\s*\{.*?\};", "", body, flags=re.S)
    rest = re.sub(r"/\*.*?\*/", "", rest, flags=re.S)
    for stmt in [s.strip() for s in rest.split(";") if s.strip()]:
        s = re.sub(r"^double\s+", "", stmt)
        s = pow_to_caret(s)
        for an in names:
            s = re.sub(r"\b%s\[([^\]]+)\]" % an, r"%s[(\1) + 1]" % an, s)
        if s.startswith("return "):
            out.append("  " + s[len("return "):]); continue
        mm = re.match(r"(\w+)\s*\+=\s*(.+)$", s)
        if mm:
            out.append("  %s <- %s + %s" % (mm.group(1), mm.group(1), mm.group(2))); continue
        mm = re.match(r"(\w+)\s*=\s*(.+)$", s)
        if mm:
            out.append("  %s <- %s" % (mm.group(1), mm.group(2))); continue
        raise ValueError("untranslated statement in %s: %r" % (name, stmt))
    out.append("}")
    return "\n".join(out), params

srcdir, outfile = sys.argv[1], sys.argv[2]
chunks = ["# Generated by data-raw/translate_c.py from the QFracture-2012 C source",
          "# (ClinRisk Ltd, LGPL-3; github.com/nhsland/clinrisk-modules 4e7cb71e). Do not edit.", ""]
sigs = []
for fn, name in FILES:
    code, params = translate(open(os.path.join(srcdir, fn)).read(), name)
    chunks.append(code); chunks.append("")
    sigs.append("  %s = c(%s)" % (name, ", ".join('"%s"' % p for p in params)))
chunks.append(".qf_params <- list(\n" + ",\n".join(sigs) + ")")
open(outfile, "w").write("\n".join(chunks) + "\n")
print("wrote", outfile)
